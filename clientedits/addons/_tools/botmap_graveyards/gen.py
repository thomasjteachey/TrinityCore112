"""Bake CENTURION_BotMap_Graveyards.lua - every graveyard, placed on its zone maps.

    python gen.py <inputs dir> <out .lua> [--dropped] [--fallbacks]

Inputs, all in <inputs dir>:

  gy_zones.txt      "<graveyard id> <ghost zone>" per line: graveyard_zone rows a
                    player can use (Faction <> 67 - every race is Alliance here),
                    unioned over lplusworld, bplusworld and centurionworld.
                    On 2026-10-18 all three held the same 575 ids.
  WorldSafeLocs.dbc a realm's data/dbc copy. Positions were identical on all
  Map.dbc           three realms for every id above.
  WorldMapArea.dbc  the CLIENT's winning copy - its rectangles are what the
                    map art is drawn in. patch-M (dungeon maps) on the B+ realms;
                    patch-enUS-8 (L+) differs only by float rounding.
  AreaTable.dbc     the client's, for subzone -> zone and zone -> map.

The coordinates are Map2ZoneCoordinates (DBCStores.cpp) divided by 100, i.e. the
same 0..1 space GetPlayerMapPosition answers in and CENTURION_BotMap draws in.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dbc import read_dbc, u32, worldsafelocs, worldmaparea, maps

src, out = sys.argv[1], sys.argv[2]
wsl = worldsafelocs(os.path.join(src, 'WorldSafeLocs.dbc'))
mp = maps(os.path.join(src, 'Map.dbc'))
wma = worldmaparea(os.path.join(src, 'WorldMapArea.dbc'))

# A zero-size rectangle is a zone with no drawable map.
zones = {wid: v for wid, v in wma.items()
         if v['area'] != 0 and v['right'] != v['left'] and v['bottom'] != v['top']}

area_parent = {}
area_map = {}
rows, _, _ = read_dbc(os.path.join(src, 'AreaTable.dbc'))
for r in rows:
    area_parent[u32(r, 0)] = u32(r, 2)
    area_map[u32(r, 0)] = u32(r, 1)


def top_zone(area):
    seen = set()
    while area_parent.get(area) and area not in seen:
        seen.add(area)
        area = area_parent[area]
    return area


# Which zones each graveyard SERVES, lifted to the top-level zone (a few rows
# name a subzone).
serves = {}
for line in open(os.path.join(src, 'gy_zones.txt')):
    gid, zone = map(int, line.split())
    serves.setdefault(gid, set()).add(top_zone(zone))


def real_zone(zone):
    # Not a battleground or arena, and not the Twisting Nether (3540), whose
    # "graveyards" are corpse catchers for a fall off Outland.
    return zone != 3540 and mp.get(area_map.get(zone), {}).get('type') not in (3, 4)


per_zone = {}
unplaced = []
skipped_pvp = fallback = notgy = 0
for gid in sorted(serves):
    if gid not in wsl:
        unplaced.append((gid, 'no WorldSafeLocs row'))
        continue
    mapid, x, y, z, name = wsl[gid]
    if 'Do Not Bug' in name:     # Blizzard's GM-only test graveyard
        notgy += 1
        continue
    if mp.get(mapid, {}).get('type') in (3, 4):
        # Battleground / arena maps: their graveyards change hands, and the
        # battleground draws its own.
        skipped_pvp += 1
        continue

    # Every zone map whose rectangle contains it.
    inside = []
    for wid, v in zones.items():
        if v['map'] != mapid:
            continue
        nx = (y - v['left']) / (v['right'] - v['left'])
        ny = (x - v['top']) / (v['bottom'] - v['top'])
        if 0.0 <= nx <= 1.0 and 0.0 <= ny <= 1.0:
            inside.append((wid, nx, ny))
    if not inside:
        unplaced.append((gid, '%s map %d %.0f %.0f' % (name, mapid, x, y)))
        continue

    # Rectangles overlap their neighbours, so "inside" alone would put Barrens
    # graveyards in Durotar's corners. Keep the maps of the zones it serves.
    home = [e for e in inside if zones[e[0]]['area'] in serves[gid]]
    if not home:
        # It serves none of the maps it sits on. Mostly that is not a spirit
        # healer at all - battleground exit points, Nether corpse catchers. The
        # rest is real (a dungeon's graveyard outside its door, Hearthglen
        # serving the Eastern Plaguelands) and goes on the one map it sits most
        # squarely inside.
        if not any(real_zone(zone) for zone in serves[gid]):
            notgy += 1
            if '--dropped' in sys.argv:
                print('DROP', gid, name, sorted(serves[gid]))
            continue
        fallback += 1
        home = [min(inside, key=lambda e: max(abs(e[1] - 0.5), abs(e[2] - 0.5)))]
        if '--fallbacks' in sys.argv:
            print('FALLBACK', gid, name, sorted(serves[gid]), zones[home[0][0]]['name'])
    for wid, nx, ny in home:
        per_zone.setdefault(wid, []).append((nx, ny, name.strip(), gid))


def lua_str(t):
    return '"' + t.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = [
    '-- GENERATED by clientedits/addons/_tools/botmap_graveyards/gen.py - do not',
    '-- edit by hand; see that script for where every input comes from.',
    '--',
    '-- Every graveyard a player can be sent to, on the map of each zone it serves,',
    '-- in the same 0..1 coordinates GetPlayerMapPosition answers in. Keyed by',
    '-- WorldMapArea.ID; each entry is { x, y, name } with the graveyard id after it.',
    'CENTURION_BOTMAP_GRAVEYARDS = {',
]
total = 0
for wid in sorted(per_zone):
    lines.append('\t[%d] = { -- %s' % (wid, zones[wid]['name']))
    for nx, ny, name, gid in sorted(per_zone[wid], key=lambda e: e[3]):
        lines.append('\t\t{ %.4f, %.4f, %s }, -- %d' % (nx, ny, lua_str(name), gid))
        total += 1
    lines.append('\t},')
lines.append('}')
with open(out, 'w', newline='\n', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')

print('graveyards', len(serves), 'pvp maps', skipped_pvp, 'not graveyards', notgy,
      'fallback', fallback, 'zones', len(per_zone), 'placements', total)
for u in unplaced:
    print('unplaced', *u)
